using System.Globalization;
using System.Text;

namespace CrestCore.Generator;

/// Emits `crest_contracts.ts`: the contract's types and wire codec in
/// TypeScript, for a platform whose interface is a web page, such as the
/// Linux WebUI. It covers what the Swift models cover, every root and every
/// record, enum and fixed set, and uses `DataView`, `Uint8Array` and the
/// platform's UTF-8 coders alone.
///
/// A record is a readonly interface with camelCase fields. A root is a union
/// of `{ kind, value }` pairs, `kind` being the member's name, because a
/// member may itself carry a field named `Kind`. An enum is the union of its
/// members' names, or a number when it is a set of flags. A fixed set is the
/// union of its members' names, with each member's data in the `facts` of the
/// constant that shares the set's name. A GUID is its lowercase hyphenated text, a 64-bit integer a `bigint`, and a
/// date the seconds the wire carries, so every value encodes to the bytes it
/// was decoded from.
internal static class TypeScriptEmitter {
    #region Static Variables

    /// What a record with a seed adds to its name for the seed's interface.
    private const string SeedSuffix = "Seed";

    /// The names the wire runtime declares and the globals it uses, which no
    /// contract type may take.
    private static readonly string[] RuntimeNames = [
        "Guid", "WireDate", "WireDuration", "LocalizedText", "WireError", "WireWriter", "WireReader", "AnswerCodec",
        "Uint8Array", "DataView", "Error", "Date", "Number", "BigInt", "Math", "String", "Array", "TextEncoder", "TextDecoder",
        "Record", "Readonly", "Partial", "Extract"
    ];

    private const string Header = """
        // <auto-generated/>
        // Generated by CrestCore/tools/CrestCore.Generator from the C# contract records. Do not edit.
        //
        // The contract in TypeScript: the intents and queries a platform sends
        // the core, the changes, rejections and answers it gets back, the engine
        // contract's messages, and the records, enums and fixed sets they hold,
        // with their positional wire codec. Lengths, counts, tags and enums are LEB128
        // varints; numbers are fixed-width little-endian; a GUID is 16 bytes in
        // RFC 4122 order; a string is its UTF-8 length and bytes; a date or a
        // duration is f64 seconds, a date since 1 January 2001; an optional is a
        // presence byte; a union is its member's tag, the member's index in its
        // root in ordinal name order, followed by the member's fields.

        """;

    private const string Runtime = """

        // Wire

        /** A GUID as lowercase hyphenated hexadecimal, such as `00112233-4455-6677-8899-aabbccddeeff`. */
        export type Guid = string;

        /** A date as the wire carries it: seconds since 1 January 2001 UTC. */
        export type WireDate = number;

        /** A duration in seconds. */
        export type WireDuration = number;

        /** Seconds from the Unix epoch to the wire's reference date, 1 January 2001 UTC. */
        export const referenceDateUnixSeconds = 978307200;

        /** The moment a wire date names, to the millisecond a `Date` keeps. */
        export function dateFromWire(value: WireDate): Date {
            return new Date((value + referenceDateUnixSeconds) * 1000);
        }

        export function dateToWire(value: Date): WireDate {
            return value.getTime() / 1000 - referenceDateUnixSeconds;
        }

        /**
         * User-facing English text and the note for its translators. Where the text
         * spells `%lld` it carries a number: `argument`, or one the core supplies.
         */
        export interface LocalizedText {
            readonly text: string;
            readonly comment?: string;
            readonly argument?: number;
        }

        /** Bytes that are not a contract message, or a value the wire cannot carry. */
        export class WireError extends Error {
            constructor(message: string) {
                super(message);
                this.name = "WireError";
            }
        }

        const maximumTag = 0x7fffffff;
        const utf8Encoder = new TextEncoder();
        const utf8Decoder = new TextDecoder("utf-8", { fatal: true, ignoreBOM: true });
        const guidPattern = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
        const hexPairs: readonly string[] = Array.from({ length: 256 }, (_, value) => value.toString(16).padStart(2, "0"));

        /** Writes the positional contract wire format that `WireReader` reads. */
        export class WireWriter {
            private buffer = new Uint8Array(256);
            private view = new DataView(this.buffer.buffer);
            private length = 0;

            /** A copy of what was written. */
            bytes(): Uint8Array {
                return this.buffer.slice(0, this.length);
            }

            /** Makes room for `count` more bytes and answers where they start. */
            private reserve(count: number): number {
                const start = this.length;
                const needed = start + count;
                if (needed > this.buffer.length) {
                    let capacity = this.buffer.length * 2;
                    while (capacity < needed) capacity *= 2;
                    const grown = new Uint8Array(capacity);
                    grown.set(this.buffer.subarray(0, start));
                    this.buffer = grown;
                    this.view = new DataView(grown.buffer);
                }
                this.length = needed;
                return start;
            }

            varint(value: number): void {
                if (!Number.isSafeInteger(value) || value < 0) throw new WireError(`${value} is not a varint.`);
                let remaining = value;
                do {
                    const next = remaining % 128;
                    remaining = Math.floor(remaining / 128);
                    const at = this.reserve(1);
                    this.buffer[at] = remaining === 0 ? next : next | 0x80;
                } while (remaining !== 0);
            }

            private bounded(value: number, what: string): void {
                if (!Number.isInteger(value) || value < 0 || value > maximumTag) throw new WireError(`${value} is not a ${what}.`);
                this.varint(value);
            }

            /** A union's tag. */
            tag(tag: number): void {
                this.bounded(tag, "tag");
            }

            count(count: number): void {
                this.bounded(count, "count");
            }

            /** An enum's value, or a set of flags. */
            enumeration(value: number): void {
                this.bounded(value, "enum");
            }

            /** A value that travels as its index in `all`: an enum's member or a fixed set's. */
            member<T>(all: readonly T[], value: T): void {
                const tag = all.indexOf(value);
                if (tag < 0) throw new WireError(`${String(value)} is not a member of its set.`);
                this.varint(tag);
            }

            presence(isPresent: boolean): void {
                this.bool(isPresent);
            }

            bool(value: boolean): void {
                const at = this.reserve(1);
                this.buffer[at] = value ? 1 : 0;
            }

            /** A C# `int`: four bytes. */
            int32(value: number): void {
                if (!Number.isInteger(value) || value < -0x80000000 || value > 0x7fffffff) {
                    throw new WireError(`${value} does not fit the contract's 32-bit int.`);
                }
                const at = this.reserve(4);
                this.view.setInt32(at, value, true);
            }

            int64(value: bigint): void {
                if (BigInt.asIntN(64, value) !== value) throw new WireError(`${value} does not fit a 64-bit int.`);
                const at = this.reserve(8);
                this.view.setBigInt64(at, value, true);
            }

            uint64(value: bigint): void {
                if (BigInt.asUintN(64, value) !== value) throw new WireError(`${value} does not fit an unsigned 64-bit int.`);
                const at = this.reserve(8);
                this.view.setBigUint64(at, value, true);
            }

            double(value: number): void {
                const at = this.reserve(8);
                this.view.setFloat64(at, value, true);
            }

            string(value: string): void {
                this.byteString(utf8Encoder.encode(value));
            }

            /** A byte string: its length, then the bytes as they are. */
            byteString(value: Uint8Array): void {
                this.count(value.length);
                const at = this.reserve(value.length);
                this.buffer.set(value, at);
            }

            guid(value: Guid): void {
                if (!guidPattern.test(value)) throw new WireError(`${value} is not a GUID.`);
                const digits = value.replace(/-/g, "");
                const at = this.reserve(16);
                for (let index = 0; index < 16; index++) this.buffer[at + index] = parseInt(digits.substring(index * 2, index * 2 + 2), 16);
            }

            date(value: WireDate): void {
                this.double(value);
            }

            duration(value: WireDuration): void {
                this.double(value);
            }

            list<T>(items: readonly T[], write: (item: T) => void): void {
                this.count(items.length);
                for (const item of items) write(item);
            }

            optional<T>(value: T | null | undefined, write: (present: T) => void): void {
                if (value === null || value === undefined) {
                    this.presence(false);
                } else {
                    this.presence(true);
                    write(value);
                }
            }
        }

        /**
         * Reads what `WireWriter` writes. Every length is checked against the bytes
         * that remain, and anything malformed throws `WireError`.
         */
        export class WireReader {
            private readonly source: Uint8Array;
            private readonly view: DataView;
            private position = 0;

            constructor(bytes: Uint8Array) {
                this.source = bytes;
                this.view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
            }

            get remaining(): number {
                return this.source.length - this.position;
            }

            /** Fails unless every byte was read. */
            finish(): void {
                if (this.remaining !== 0) throw new WireError(`${this.remaining} unexpected trailing bytes.`);
            }

            /** Passes over `count` bytes and answers where they start. */
            private take(count: number): number {
                if (count > this.remaining) throw new WireError("Truncated message.");
                const start = this.position;
                this.position += count;
                return start;
            }

            /** A varint. One past 2^53 is inexact, and every bound it is held to is far below that. */
            varint(): number {
                let value = 0;
                let scale = 1;
                for (let shift = 0; shift < 64; shift += 7) {
                    const next = this.source[this.take(1)] as number;
                    const bits = next & 0x7f;
                    if (shift === 63 && bits > 1) throw new WireError("Varint overflow.");
                    value += bits * scale;
                    scale *= 128;
                    if ((next & 0x80) === 0) {
                        if (next === 0 && shift > 0) throw new WireError("Overlong varint.");
                        return value;
                    }
                }
                throw new WireError("Varint overflow.");
            }

            private bounded(maximum: number, what: string): number {
                const value = this.varint();
                if (value > maximum) throw new WireError(`The ${what} ${value} exceeds ${maximum}.`);
                return value;
            }

            /** A union's tag. */
            tag(): number {
                return this.bounded(maximumTag, "tag");
            }

            /** A list's count. Every element occupies at least one byte. */
            count(): number {
                return this.bounded(this.remaining, "count");
            }

            /** A value that travels as its index in `all`: an enum's member or a fixed set's. */
            member<T>(all: readonly T[]): T {
                return all[this.bounded(all.length - 1, "enum")] as T;
            }

            /** A set of flags, which may only set bits in `mask`. */
            flags(mask: number): number {
                const value = this.bounded(maximumTag, "flags");
                if ((value & ~mask) !== 0) throw new WireError(`Unknown flags ${value}.`);
                return value;
            }

            presence(): boolean {
                return this.flag("presence");
            }

            bool(): boolean {
                return this.flag("bool");
            }

            private flag(what: string): boolean {
                const value = this.source[this.take(1)] as number;
                if (value > 1) throw new WireError(`A ${what} byte is ${value}.`);
                return value === 1;
            }

            /** A C# `int`: four bytes. */
            int32(): number {
                return this.view.getInt32(this.take(4), true);
            }

            int64(): bigint {
                return this.view.getBigInt64(this.take(8), true);
            }

            uint64(): bigint {
                return this.view.getBigUint64(this.take(8), true);
            }

            double(): number {
                return this.view.getFloat64(this.take(8), true);
            }

            string(): string {
                const length = this.bounded(this.remaining, "string length");
                const start = this.take(length);
                try {
                    return utf8Decoder.decode(this.source.subarray(start, start + length));
                } catch {
                    throw new WireError("A string is not UTF-8.");
                }
            }

            /** A byte string, copied out of the message. */
            byteString(): Uint8Array {
                const length = this.bounded(this.remaining, "byte length");
                const start = this.take(length);
                return this.source.slice(start, start + length);
            }

            guid(): Guid {
                const start = this.take(16);
                let text = "";
                for (let index = 0; index < 16; index++) {
                    if (index === 4 || index === 6 || index === 8 || index === 10) text += "-";
                    text += hexPairs[this.source[start + index] as number] as string;
                }
                return text;
            }

            date(): WireDate {
                return this.seconds("date");
            }

            duration(): WireDuration {
                return this.seconds("duration");
            }

            private seconds(what: string): number {
                const seconds = this.double();
                if (!Number.isFinite(seconds)) throw new WireError(`A ${what} is not finite.`);
                return seconds;
            }

            list<T>(read: () => T): readonly T[] {
                const count = this.count();
                const items: T[] = [];
                for (let index = 0; index < count; index++) items.push(read());
                return items;
            }

            optional<T>(read: () => T): T | null {
                return this.presence() ? read() : null;
            }
        }

        /** How the answer to one question crosses the wire. */
        interface AnswerCodec<T> {
            readonly decode: (r: WireReader) => T;
            readonly encode: (w: WireWriter, v: T) => void;
        }

        """;

    #endregion

    #region Actions - Emitting

    public static string Emit(ContractSchema schema) {
        ArgumentNullException.ThrowIfNull(schema);
        EnsureDistinctNames(schema);
        var code = new StringBuilder(Header);
        code.Append(Runtime);
        code.Append("\n// Schema\n");
        code.Append($"\nexport const wireVersion = {ContractSchema.WireVersion};\n");
        code.Append("\n/** SHA-256 of the canonical contract schema. The core refuses any other. */\n");
        code.Append($"export const fingerprint: Uint8Array = new Uint8Array([\n    {Bytes(schema.Fingerprint)},\n]);\n");
        code.Append("\n/** SHA-256 of the engine contract alone, which an engine binding registers with. */\n");
        code.Append($"export const engineFingerprint: Uint8Array = new Uint8Array([\n    {Bytes(schema.EngineFingerprint)},\n]);\n");

        code.Append("\n// Roots\n");
        var roots = ContractRoot.All.Where(root => schema.Members(root).Count > 0).ToList();
        foreach (var root in roots) EmitRoot(code, schema, root);
        var narrowed = schema.Bases.Select(family => family.Base!).ToHashSet();
        foreach (var family in schema.Families.Concat(schema.Bases).DistinctBy(family => family.Base)
            .OrderBy(family => family.Base!.Name, StringComparer.Ordinal))
            EmitFamily(code, schema, family, isNarrowed: narrowed.Contains(family.Base!));
        foreach (var root in roots.Where(root => root.HasAnswer)) EmitAnswers(code, schema, root);
        foreach (var root in roots.Where(root => schema.Members(root).Any(member => member.Record.Texts.Count > 0)))
            EmitRootTexts(code, schema, root);

        code.Append("\n// Records\n");
        foreach (var record in schema.Records) EmitRecord(code, schema, record);

        if (schema.Enums.Count > 0) code.Append("\n// Enums\n");
        foreach (var item in schema.Enums) EmitEnum(code, item);

        if (schema.Sets.Count > 0) code.Append("\n// Fixed sets\n");
        foreach (var set in schema.Sets) EmitSet(code, set);
        return code.ToString();
    }

    /// Every type the file exports is named as a contract type is or after
    /// one, as a record's seed is, and TypeScript has one namespace for them
    /// all. A constant shares its type's name, so it needs none of its own.
    private static void EnsureDistinctNames(ContractSchema schema) {
        var names = new HashSet<string>(RuntimeNames, StringComparer.Ordinal);
        void Declare(string name) {
            if (!names.Add(name))
                throw new ContractSchemaException($"{name}: the TypeScript contracts already declare or use this name.");
        }
        foreach (var root in ContractRoot.All) {
            Declare(root.Name);
            if (root.HasAnswer) Declare($"{root.Name}Answers");
        }
        foreach (var family in schema.Families.Concat(schema.Bases).DistinctBy(family => family.Base)) Declare(family.Base!.Name);
        foreach (var record in schema.Records) {
            Declare(record.Name);
            if (schema.HasSeed(record.Type)) Declare($"{record.Name}{SeedSuffix}");
        }
        foreach (var item in schema.Enums) Declare(item.Name);
        foreach (var set in schema.Sets) Declare(set.Name);
    }

    private static string Bytes(byte[] bytes) => string.Join(", ", bytes.Select(value => $"0x{value:x2}"));

    #endregion

    #region Actions - Roots

    /// A root is the union of its members, each paired with its name, and
    /// travels as the member's tag followed by the member's fields.
    private static void EmitRoot(StringBuilder code, ContractSchema schema, ContractRoot root) {
        var members = schema.Members(root);
        string direction = root.PlatformSends ? "A platform sends it." : "A platform receives it.";
        code.Append('\n').Append($"/** One of the core's `{root}` messages; `kind` names which. {direction} */\n");
        code.Append($"export type {root} =\n");
        code.Append(string.Join('\n', members.Select(member =>
            $"    | {{ readonly kind: \"{member.Name}\"; readonly value: {member.Name} }}"))).Append(";\n");

        code.Append('\n').Append($"export function decode{root}(r: WireReader): {root} {{\n");
        code.Append("    const tag = r.tag();\n    switch (tag) {\n");
        foreach (var member in members)
            code.Append($"        case {member.Tag}: return {{ kind: \"{member.Name}\", value: decode{member.Name}(r) }};\n");
        code.Append($"        default: throw new WireError(`Unknown {root} tag ${{tag}}.`);\n    }}\n}}\n");

        code.Append('\n').Append($"export function encode{root}(w: WireWriter, m: {root}): void {{\n");
        code.Append("    switch (m.kind) {\n");
        foreach (var member in members)
            code.Append($"        case \"{member.Name}\": w.tag({member.Tag}); encode{member.Name}(w, m.value); break;\n");
        code.Append($"        default: throw new WireError(`${{String((m as {{ kind: unknown }}).kind)}} is not a contract {root}.`);\n");
        code.Append("    }\n}\n");
    }

    /// The members of a root that derive from one abstract record. A field
    /// narrowed to it reads only their tags, and writes as its root does.
    private static void EmitFamily(StringBuilder code, ContractSchema schema, RootField family, bool isNarrowed) {
        string name = family.Base!.Name;
        var members = schema.Members(family);
        code.Append('\n').Append($"/** The members of `{family.Root}` that derive from the core's `{name}`. */\n");
        code.Append($"export type {name} = Extract<{family.Root}, {{ kind: {string.Join(" | ", members.Select(member => $"\"{member.Name}\""))} }}>;\n");
        if (!isNarrowed) return;
        code.Append('\n').Append($"export function decode{name}(r: WireReader): {name} {{\n");
        code.Append("    const tag = r.tag();\n    switch (tag) {\n");
        foreach (var member in members)
            code.Append($"        case {member.Tag}: return {{ kind: \"{member.Name}\", value: decode{member.Name}(r) }};\n");
        code.Append($"        default: throw new WireError(`{family.Root} tag ${{tag}} is not a {name}.`);\n    }}\n}}\n");
    }

    /// The answer each question of a root is answered with, by the question's
    /// name, and how each answer crosses the wire.
    private static void EmitAnswers(StringBuilder code, ContractSchema schema, ContractRoot root) {
        var members = schema.Members(root);
        string codecs = $"{char.ToLowerInvariant(root.Name[0])}{root.Name[1..]}AnswerCodecs";
        code.Append('\n').Append($"/** What each `{root}` is answered with, by its `kind`. */\n");
        code.Append($"export interface {root}Answers {{\n");
        foreach (var member in members) code.Append($"    readonly {member.Name}: {TypeName(member.Answer!)};\n");
        code.Append("}\n");
        code.Append('\n').Append($"const {codecs}: {{ readonly [K in keyof {root}Answers]: AnswerCodec<{root}Answers[K]> }} = {{\n");
        foreach (var member in members)
            code.Append($"    {member.Name}: {{ decode: (r) => {Read(member.Answer!)}, encode: (w, v) => {Write(member.Answer!, "v", 0)} }},\n");
        code.Append("};\n");
        code.Append('\n').Append($"export function decode{root}Answer<K extends keyof {root}Answers>(kind: K, r: WireReader): {root}Answers[K] {{\n");
        code.Append($"    return {codecs}[kind].decode(r);\n}}\n");
        code.Append('\n').Append($"export function encode{root}Answer<K extends keyof {root}Answers>(w: WireWriter, kind: K, v: {root}Answers[K]): void {{\n");
        code.Append($"    {codecs}[kind].encode(w, v);\n}}\n");
    }

    /// The texts a message of a root carries, by name; none for a member
    /// without any.
    private static void EmitRootTexts(StringBuilder code, ContractSchema schema, ContractRoot root) {
        var carriers = schema.Members(root).Where(member => member.Record.Texts.Count > 0).ToList();
        var names = carriers.SelectMany(member => member.Record.Texts).Select(text => $"\"{Member(text.Name)}\"").Distinct()
            .Order(StringComparer.Ordinal);
        code.Append('\n').Append($"/** The user-facing English texts a `{root}` carries, by name. */\n");
        code.Append($"export function textsOf{root}(m: {root}): Readonly<Partial<Record<{string.Join(" | ", names)}, LocalizedText>>> {{\n");
        code.Append("    switch (m.kind) {\n");
        foreach (var member in carriers) code.Append($"        case \"{member.Name}\": return textsOf{member.Name}(m.value);\n");
        code.Append("        default: return {};\n    }\n}\n");
    }

    #endregion

    #region Actions - Records

    /// A record crosses the wire from the core as its fields and then the
    /// values the core resolves from them. A message the platform sends holds
    /// seeds, and a record that has one also declares it: its fields alone,
    /// with seeds in them.
    private static void EmitRecord(StringBuilder code, ContractSchema schema, ContractRecord record) {
        bool sent = schema.IsSent(record);
        EmitRecordCodec(code, schema, record.Name, record.Wire, seeds: sent,
            documentation: $"The core's `{record.Name}`.");
        if (schema.HasSeed(record.Type))
            EmitRecordCodec(code, schema, $"{record.Name}{SeedSuffix}", record.Fields, seeds: true,
                documentation: $"The fields of a `{record.Name}` alone, as a platform sends one. The core resolves the rest when it reads it.");
        if (record.Statics.Count > 0) {
            code.Append('\n').Append($"/** The values the core's `{record.Name}` names. */\n");
            code.Append($"export const {record.Name}: {ConstantsType(record.Statics, "")} = {ConstantsLiteral(record.Statics, "")};\n");
        }
        if (record.Texts.Count > 0) EmitRecordTexts(code, record);
    }

    private static void EmitRecordCodec(StringBuilder code, ContractSchema schema, string name, IReadOnlyList<ContractField> wire,
        bool seeds, string documentation) {
        code.Append('\n').Append($"/** {documentation} */\n");
        if (wire.Count == 0) {
            code.Append($"export interface {name} {{}}\n");
            code.Append('\n').Append($"export function decode{name}(_r: WireReader): {name} {{\n    return {{}};\n}}\n");
            code.Append('\n').Append($"export function encode{name}(_w: WireWriter, _v: {name}): void {{}}\n");
            return;
        }
        code.Append($"export interface {name} {{\n");
        foreach (var field in wire) code.Append($"    readonly {Member(field.Name)}: {TypeName(field.Type, schema, seeds)};\n");
        code.Append("}\n");
        code.Append('\n').Append($"export function decode{name}(r: WireReader): {name} {{\n    return {{\n");
        foreach (var field in wire) code.Append($"        {Member(field.Name)}: {Read(field.Type, schema, seeds)},\n");
        code.Append("    };\n}\n");
        code.Append('\n').Append($"export function encode{name}(w: WireWriter, v: {name}): void {{\n");
        foreach (var field in wire) code.Append($"    {Write(field.Type, $"v.{Member(field.Name)}", 0, schema, seeds)};\n");
        code.Append("}\n");
    }

    /// A record's texts are the same English for every instance, each carrying
    /// the record's own field where it spells `%lld`.
    private static void EmitRecordTexts(StringBuilder code, ContractRecord record) {
        string value = record.Texts.Any(text => text.Argument is not null) ? "v" : "_v";
        code.Append('\n').Append($"/** The user-facing English texts of a `{record.Name}`. */\n");
        code.Append($"export function textsOf{record.Name}({value}: {record.Name}): "
            + $"{{ {string.Join("; ", record.Texts.Select(text => $"readonly {Member(text.Name)}: LocalizedText"))} }} {{\n");
        code.Append("    return {\n");
        foreach (var text in record.Texts)
            code.Append($"        {Member(text.Name)}: {LocalizedLiteral(text.Text, text.Comment, text.Argument is { } argument ? $"v.{Member(argument)}" : null)},\n");
        code.Append("    };\n}\n");
    }

    /// The type of an object of named values, closing at `indent`.
    private static string ConstantsType(IReadOnlyList<ContractConstant> constants, string indent) =>
        $"{{\n{string.Concat(constants.Select(constant =>
            $"{indent}    readonly {Member(constant.Name)}: {TypeName(constant.Type)};\n"))}{indent}}}";

    /// An object of named values, closing at `indent`.
    private static string ConstantsLiteral(IReadOnlyList<ContractConstant> constants, string indent) =>
        $"{{\n{string.Concat(constants.Select(constant =>
            $"{indent}    {Member(constant.Name)}: {Literal(constant.Type, constant.Value)},\n"))}{indent}}}";

    #endregion

    #region Actions - Enums and fixed sets

    /// A plain enum is the union of its members' names and travels as the
    /// member's value, its index among them. A flags enum is a number, with
    /// its named bits beside it.
    private static void EmitEnum(StringBuilder code, ContractEnum item) {
        if (item.IsFlags) {
            int mask = item.Members.Aggregate(0, (bits, member) => bits | member.Value);
            code.Append('\n').Append($"/** A set of the core's `{item.Name}` flags, whose bits `{item.Name}` names. */\n");
            code.Append($"export type {item.Name} = number;\n");
            code.Append($"export const {item.Name} = {{ {string.Join(", ", item.Members.Select(member => $"{member.Key}: {member.Value}"))} }} as const;\n");
            code.Append('\n').Append($"export function decode{item.Name}(r: WireReader): {item.Name} {{\n    return r.flags({mask});\n}}\n");
            code.Append('\n').Append($"export function encode{item.Name}(w: WireWriter, v: {item.Name}): void {{\n    w.enumeration(v);\n}}\n");
            return;
        }
        code.Append('\n').Append($"/** The core's `{item.Name}`. A member's wire value is its index in `{item.Name}.all`. */\n");
        EmitMembers(code, item.Name, [.. item.Members.Select(member => member.Key)]);
        code.Append($"export const {item.Name}: {{ readonly all: readonly {item.Name}[] }} = {{\n");
        code.Append($"    all: {MembersLiteral([.. item.Members.Select(member => member.Key)])},\n}};\n");
        EmitMemberCodec(code, item.Name);
    }

    /// A fixed set is the union of its members' names. The constant that
    /// shares its name lists them in `all`, where a member's index is its wire
    /// tag, and keeps each member's data in `facts` and the set's constants in
    /// `constants`. An open set also has members the core makes at runtime,
    /// which have no tag, so it never crosses the wire.
    private static void EmitSet(StringBuilder code, ContractSet set) {
        code.Append('\n').Append(set.IsOpen
            ? $"/**\n * The members of the core's `{set.Name}` that it names. It also makes members at runtime, so the set never crosses the wire."
            : $"/**\n * The members of the core's `{set.Name}`. A member's wire tag is its index in `{set.Name}.all`.");
        if (set.CoreOnly.Count > 0)
            code.Append($"\n * Core-only behavior, not emitted: {string.Join(", ", set.CoreOnly.Select(name => $"`{name}`"))}.");
        code.Append("\n */\n");
        string[] members = [.. set.Members.Select(member => member.Name)];
        EmitMembers(code, set.Name, members);
        code.Append($"export const {set.Name}: {{\n    readonly all: readonly {set.Name}[];\n");
        code.Append($"    readonly facts: Readonly<Record<{set.Name}, {{\n");
        foreach (var property in set.Properties) code.Append($"        readonly {Member(property.Name)}: {TypeName(property.Type)};\n");
        code.Append("    }>>;\n");
        if (set.Constants.Count > 0) code.Append($"    readonly constants: {ConstantsType(set.Constants, "    ")};\n");
        code.Append($"}} = {{\n    all: {MembersLiteral(members)},\n    facts: {{\n");
        foreach (var member in set.Members)
            code.Append($"        {member.Name}: {{ {string.Join(", ", set.Properties.Select((property, index) =>
                $"{Member(property.Name)}: {Literal(property.Type, member.Values[index])}"))} }},\n");
        code.Append("    },\n");
        if (set.Constants.Count > 0) code.Append($"    constants: {ConstantsLiteral(set.Constants, "    ")},\n");
        code.Append("};\n");
        if (!set.IsOpen) EmitMemberCodec(code, set.Name);
    }

    private static void EmitMembers(StringBuilder code, string name, IReadOnlyList<string> members) {
        code.Append($"export type {name} =\n");
        code.Append(string.Join('\n', members.Select(member => $"    | \"{member}\""))).Append(";\n");
    }

    private static string MembersLiteral(IReadOnlyList<string> members) => $"[{string.Join(", ", members.Select(member => $"\"{member}\""))}]";

    private static void EmitMemberCodec(StringBuilder code, string name) {
        code.Append('\n').Append($"export function decode{name}(r: WireReader): {name} {{\n    return r.member({name}.all);\n}}\n");
        code.Append('\n').Append($"export function encode{name}(w: WireWriter, v: {name}): void {{\n    w.member({name}.all, v);\n}}\n");
    }

    /// A set's nested `Kinds` enum as the union of its members' names.
    private static string KindsType(KindsField kinds) => string.Join(" | ", Enum.GetNames(kinds.Type).Select(kind => $"\"{kind}\""));

    #endregion

    #region Actions - Fields

    private static string Member(string name) => Naming.TypeScriptMember(name);

    /// The expression that reads a field. With `seeds`, a record that has a
    /// seed reads as it.
    private static string Read(FieldType type, ContractSchema? schema = null, bool seeds = false) => type switch {
        PrimitiveField primitive => $"r.{Method(primitive.Kind)}()",
        EnumField item => $"decode{item.Type.Name}(r)",
        SetField set => $"decode{set.Type.Name}(r)",
        RecordField record => $"decode{record.Type.Name}{Seed(record, schema, seeds)}(r)",
        RootField { Base: { } narrowed } => $"decode{narrowed.Name}(r)",
        RootField root => $"decode{root.Root}(r)",
        ListField list => $"r.list(() => {Read(list.Element, schema, seeds)})",
        OptionalField optional => $"r.optional(() => {Read(optional.Value, schema, seeds)})",
        _ => throw new ContractSchemaException($"Unknown field type {type}.")
    };

    /// The expression that writes `value`. A list's element and an optional's
    /// value are named by how deeply they nest.
    private static string Write(FieldType type, string value, int depth, ContractSchema? schema = null, bool seeds = false) => type switch {
        PrimitiveField primitive => $"w.{Method(primitive.Kind)}({value})",
        EnumField item => $"encode{item.Type.Name}(w, {value})",
        SetField set => $"encode{set.Type.Name}(w, {value})",
        RecordField record => $"encode{record.Type.Name}{Seed(record, schema, seeds)}(w, {value})",
        RootField root => $"encode{root.Root}(w, {value})",
        ListField list => $"w.list({value}, (e{depth}) => {Write(list.Element, $"e{depth}", depth + 1, schema, seeds)})",
        OptionalField optional => $"w.optional({value}, (p{depth}) => {Write(optional.Value, $"p{depth}", depth + 1, schema, seeds)})",
        _ => throw new ContractSchemaException($"Unknown field type {type}.")
    };

    /// The suffix of a record's seed, where `seeds` asks for one and the
    /// record has one.
    private static string Seed(RecordField record, ContractSchema? schema, bool seeds) =>
        seeds && schema!.HasSeed(record.Type) ? SeedSuffix : "";

    /// The reader's and the writer's method for a primitive.
    private static string Method(Primitive kind) => kind switch {
        Primitive.Bool => "bool",
        Primitive.Int => "int32",
        Primitive.Long => "int64",
        Primitive.ULong => "uint64",
        Primitive.Double => "double",
        Primitive.String => "string",
        Primitive.Guid => "guid",
        Primitive.Date => "date",
        Primitive.Duration => "duration",
        Primitive.Bytes => "byteString",
        _ => throw new ContractSchemaException($"Unknown primitive {kind}.")
    };

    /// A field's TypeScript type. With `seeds`, a record that has a seed is it.
    private static string TypeName(FieldType type, ContractSchema? schema = null, bool seeds = false) => type switch {
        PrimitiveField { Kind: Primitive.Bool } => "boolean",
        PrimitiveField { Kind: Primitive.Int or Primitive.Double } => "number",
        PrimitiveField { Kind: Primitive.Long or Primitive.ULong } => "bigint",
        PrimitiveField { Kind: Primitive.String } => "string",
        PrimitiveField { Kind: Primitive.Guid } => "Guid",
        PrimitiveField { Kind: Primitive.Date } => "WireDate",
        PrimitiveField { Kind: Primitive.Duration } => "WireDuration",
        PrimitiveField { Kind: Primitive.Bytes } => "Uint8Array",
        EnumField item => item.Type.Name,
        SetField set => set.Type.Name,
        LocalizedField => "LocalizedText",
        KindsField kinds => KindsType(kinds),
        RecordField record => $"{record.Type.Name}{Seed(record, schema, seeds)}",
        RootField { Base: { } narrowed } => narrowed.Name,
        RootField root => root.Root.Name,
        ListField { Element: OptionalField or KindsField or ListField } list => $"readonly ({TypeName(list.Element, schema, seeds)})[]",
        ListField list => $"readonly {TypeName(list.Element, schema, seeds)}[]",
        OptionalField optional => $"{TypeName(optional.Value, schema, seeds)} | null",
        _ => throw new ContractSchemaException($"Unknown field type {type}.")
    };

    #endregion

    #region Actions - Literals

    /// A fixed set member's data value, or a record's static value, as a
    /// TypeScript literal. A member of a set or an enum is its name, a flags
    /// value its number, a duration its seconds and a record an object of its
    /// wire fields.
    private static string Literal(FieldType type, object? value) => (type, value) switch {
        (OptionalField, null) => "null",
        (OptionalField optional, _) => Literal(optional.Value, value),
        (PrimitiveField, bool flag) => flag ? "true" : "false",
        (PrimitiveField, int number) => number.ToString(CultureInfo.InvariantCulture),
        (PrimitiveField, long or ulong) => $"{Convert.ToString(value, CultureInfo.InvariantCulture)}n",
        (PrimitiveField, double number) => DoubleLiteral(number),
        (PrimitiveField, TimeSpan duration) => DoubleLiteral(duration.TotalSeconds),
        (PrimitiveField, string text) => StringLiteral(text),
        (SetField, SetMemberReference reference) => $"\"{reference.Member}\"",
        (KindsField, Enum kind) => $"\"{kind}\"",
        (EnumField item, Enum member) => item.Type.IsDefined(typeof(FlagsAttribute), false)
            ? Convert.ToInt64(member, CultureInfo.InvariantCulture).ToString(CultureInfo.InvariantCulture)
            : $"\"{member}\"",
        (ListField list, IReadOnlyList<object?> items) => $"[{string.Join(", ", items.Select(item => Literal(list.Element, item)))}]",
        (RecordField, RecordValue record) => record.Record.Wire.Count == 0 ? "{}" : $"{{ {string.Join(", ", record.Record.Wire.Select((field, index) =>
            $"{Member(field.Name)}: {Literal(field.Type, record.Values[index])}"))} }}",
        (LocalizedField, LocalizedText text) =>
            LocalizedLiteral(text.Text, text.Comment, text.Argument?.ToString(CultureInfo.InvariantCulture)),
        _ => throw new ContractSchemaException($"Cannot spell {value} as a TypeScript {TypeName(type)}.")
    };

    /// A `LocalizedText`: the English, the note for translators when there is
    /// one, and the expression of the number the text carries when it has one.
    private static string LocalizedLiteral(string text, string? comment, string? argument) =>
        $"{{ text: {StringLiteral(text)}{(comment is null ? "" : $", comment: {StringLiteral(comment)}")}"
        + $"{(argument is null ? "" : $", argument: {argument}")} }}";

    private static string DoubleLiteral(double number) => number switch {
        double.NaN => "NaN",
        double.PositiveInfinity => "Infinity",
        double.NegativeInfinity => "-Infinity",
        _ => number.ToString("R", CultureInfo.InvariantCulture)
    };

    private static string StringLiteral(string text) {
        var literal = new StringBuilder("\"");
        foreach (var rune in text.EnumerateRunes())
            literal.Append(rune.Value switch {
                '\\' => "\\\\",
                '"' => "\\\"",
                '\n' => "\\n",
                '\r' => "\\r",
                '\t' => "\\t",
                < 0x20 or 0x7f or 0x2028 or 0x2029 => $"\\u{{{rune.Value:x}}}",
                _ => rune.ToString()
            });
        return literal.Append('"').ToString();
    }

    #endregion
